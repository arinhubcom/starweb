// Generate src/styles/theme.css from one seed color. Run with:
// pnpm exec tsx scripts/theme.ts
// Use `tsx`, not plain `node`: `@material/material-color-utilities` 0.4.0
// imports files without `.js`, so plain Node fails.
// See the Set the colors section in rules/MATERIAL.md. Change SEED, not the output.
import { writeFileSync } from "node:fs";
import {
  argbFromHex,
  Hct,
  hexFromArgb,
  SchemeTonalSpot,
} from "@material/material-color-utilities";
import type { DynamicScheme } from "@material/material-color-utilities";

// The only color input. Do not pick theme colors by hand.
const SEED = "#6750a4";
const OUTPUT = "src/styles/theme.css";

const shadcnRoles = (s: DynamicScheme): Record<string, number> => ({
  background: s.surface,
  foreground: s.onSurface,
  card: s.surfaceContainerLow,
  "card-foreground": s.onSurface,
  popover: s.surfaceContainer,
  "popover-foreground": s.onSurface,
  primary: s.primary,
  "primary-foreground": s.onPrimary,
  secondary: s.secondaryContainer,
  "secondary-foreground": s.onSecondaryContainer,
  muted: s.surfaceContainerHighest,
  "muted-foreground": s.onSurfaceVariant,
  accent: s.secondaryContainer,
  "accent-foreground": s.onSecondaryContainer,
  destructive: s.error,
  border: s.outlineVariant,
  input: s.outline,
  ring: s.secondary,
  sidebar: s.surface,
  "sidebar-foreground": s.onSurface,
  "sidebar-primary": s.primary,
  "sidebar-primary-foreground": s.onPrimary,
  "sidebar-accent": s.secondaryContainer,
  "sidebar-accent-foreground": s.onSecondaryContainer,
  "sidebar-border": s.outlineVariant,
  "sidebar-ring": s.secondary,
});

const extraRoles = (s: DynamicScheme): Record<string, number> => ({
  "primary-container": s.primaryContainer,
  "on-primary-container": s.onPrimaryContainer,
  tertiary: s.tertiary,
  "on-tertiary": s.onTertiary,
  "tertiary-container": s.tertiaryContainer,
  "on-tertiary-container": s.onTertiaryContainer,
  "on-error": s.onError,
  "error-container": s.errorContainer,
  "on-error-container": s.onErrorContainer,
  "surface-container-lowest": s.surfaceContainerLowest,
  "surface-container-low": s.surfaceContainerLow,
  "surface-container": s.surfaceContainer,
  "surface-container-high": s.surfaceContainerHigh,
  "surface-container-highest": s.surfaceContainerHighest,
  "inverse-surface": s.inverseSurface,
  "inverse-on-surface": s.inverseOnSurface,
  "inverse-primary": s.inversePrimary,
  outline: s.outline,
  "outline-variant": s.outlineVariant,
  scrim: s.scrim,
});

// "2025" is the Expressive spec. 0 is standard contrast. `false` goes to
// `:root`, `true` goes to `.dark`.
const schemeFor = (isDark: boolean): DynamicScheme =>
  new SchemeTonalSpot(Hct.fromInt(argbFromHex(SEED)), isDark, 0, "2025");

const allRoles = (s: DynamicScheme): Record<string, number> => ({
  ...shadcnRoles(s),
  ...extraRoles(s),
});

const block = (selector: string, lines: readonly string[]): string =>
  `${selector} {\n${lines.map((line) => `  ${line}`).join("\n")}\n}\n`;

const colorBlock = (selector: string, isDark: boolean): string =>
  block(
    selector,
    Object.entries(allRoles(schemeFor(isDark))).map(
      ([name, argb]) => `--${name}: ${hexFromArgb(argb)};`,
    ),
  );

const themeBlock = block(
  "@theme inline",
  Object.keys(extraRoles(schemeFor(false))).map(
    (name) => `--color-${name}: var(--${name});`,
  ),
);

writeFileSync(
  OUTPUT,
  [
    "/* Generated by scripts/theme.ts. Change the seed and run the script again. */\n",
    colorBlock(":root", false),
    colorBlock(".dark", true),
    themeBlock,
  ].join("\n"),
);
